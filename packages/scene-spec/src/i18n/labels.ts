/** Text drawn or spoken by an engine, in the language of the lesson on screen. */
export function engineText(key: EngineTextKey, vars?: Record<string, string | number>): string {
  const s: string = isItalian(displayLocale()) ? IT[key] : EN[key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

/** Default note names of the lesson's language: Do Re Mi for the solfège languages, letters otherwise. */
export function defaultNoteNames(): "it" | "en" {
  return ["it", "fr", "es", "pt", "ro", "ca", "gl"].includes(baseLang(displayLocale())) ? "it" : "en";
}
