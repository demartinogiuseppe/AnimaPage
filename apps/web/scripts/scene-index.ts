// Index of the example scenes (fixtures/public/scenes/*.scene.json) for the home's "Esempi" list:
// writes scenes/index.json with title, subject, engine and file of each scene. Run by the Vite
// plugin in vite.config.ts at dev-server start, on every scene change in dev, and at `vite build`
// (so also in `pnpm dev:phone`). Only the default examples are listed, unless all is set; "_" (dev scenes) never.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const SCENE_INDEX_FILE = "index.json";
const SUFFIX = ".scene.json";

export interface SceneIndexEntry {
  /** Name for ?scene= (file name without ".scene.json"). */
  file: string;
  title: string;
  /** Subject as written on the scene, first letter upper-case ("Geografia"). */
  subject: string;
  engine: string;
  /** Generated by the app from a page photo (gen-*.scene.json) rather than written by hand. */
  generated: boolean;
}

/** The example lessons the home's "Esempi" list shows by default (chosen by the owner), in this order. */
export const DEFAULT_EXAMPLES = [
  "troia",
  "matematica-parabola",
  "laboratorio-energia",
  "arte-ultima-cena",
  "cielo-stagioni",
  "geometria-solidi",
  "terra-sezione",
  "musica-pentagramma",
  "officina-mulino",
  "facciata-tempio-chiesa",
];

const capitalize = (s: string) => s.charAt(0).toLocaleUpperCase("it-IT") + s.slice(1);

export interface SceneIndexOptions {
  /** List every scene (defaults first, then other hand-written ones by title, then gen-*) instead of only the defaults. */
  all?: boolean;
}

/** Reads the scenes in `dir`; unreadable files are skipped. Default: only DEFAULT_EXAMPLES that exist, in order. */
export function buildSceneIndex(dir: string, opts: SceneIndexOptions = {}): SceneIndexEntry[] {
  const out: SceneIndexEntry[] = [];
  for (const name of readdirSync(dir)) {
    if (!name.endsWith(SUFFIX) || name.startsWith("_")) continue;
    try {
      const j = JSON.parse(readFileSync(join(dir, name), "utf8")) as { title?: unknown; engine?: unknown; page?: { subject?: unknown } };
      if (typeof j.title !== "string" || typeof j.engine !== "string") continue;
      const file = name.slice(0, -SUFFIX.length);
      if (!opts.all && !DEFAULT_EXAMPLES.includes(file)) continue;
      const subject = typeof j.page?.subject === "string" ? capitalize(j.page.subject.trim()) : "Altro";
      out.push({ file, title: j.title, subject, engine: j.engine, generated: file.startsWith("gen-") });
    } catch {
      /* broken scene: not listed */
    }
  }
  const rank = (e: SceneIndexEntry) => {
    const i = DEFAULT_EXAMPLES.indexOf(e.file);
    return e.generated ? 2000 : i >= 0 ? i : 1000;
  };
  return out.sort((a, b) => rank(a) - rank(b) || a.title.localeCompare(b.title, "it"));
}

/** Writes dir/index.json; returns true when its content changed. */
export function writeSceneIndex(dir: string, opts: SceneIndexOptions = {}): boolean {
  const file = join(dir, SCENE_INDEX_FILE);
  const text = `${JSON.stringify(buildSceneIndex(dir, opts), null, 1)}\n`;
  if (existsSync(file) && readFileSync(file, "utf8") === text) return false;
  writeFileSync(file, text);
  return true;
}
