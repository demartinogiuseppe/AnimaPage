// Writes the candidates the user kept into the app: copies the OGG files, regenerates the storybook variant
// library (real file first, synth placeholder kept as fallback) and lists the licence of every file.
// Usage: pnpm sounds:accept
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { StoryVariant } from "../../packages/engine/src/engines/storybook/library.ts";
import { STORY_LIBRARY } from "../../packages/engine/src/engines/storybook/library.ts";
import { CANDIDATES_DIR, REPO_ROOT, isMain, type CandidateRow, type Decisions } from "./common.ts";

export interface AcceptOptions {
  candidatesDir: string;
  /** fixtures/public/audio/storybook */
  audioDir: string;
  /** packages/engine/src/engines/storybook/library.ts */
  libraryPath: string;
  /** docs/assets-audio-storybook.md */
  docPath: string;
  baseLibrary: Readonly<Record<string, StoryVariant>>;
  /** Size limit of the audio folder (default 12 MB). */
  budgetBytes?: number;
}

export const BUDGET_BYTES = 12_000_000;

const ROWS_MARKER = "<!-- accepted-rows -->";
const TABLE_HEAD = "| File | Group | Author | Licence | Source page |\n|---|---|---|---|---|";

const LIBRARY_HEADER = `// Variant library of the storybook sound groups (packages/scene-spec/src/storybook-sounds.ts): which
// variants exist for each group, whether a file backs them (audio/storybook/<variant>.ogg) and the
// procedural fallback used until then or when the file fails. Data only: GENERATED by
// \`pnpm sounds:accept\` (tools/sounds/accept.ts) from the sounds the user kept; edit through the pipeline.
// Each group has at least one variant; \`dur\` is the length in seconds of the synth rendering.
import type { Synth } from "../../player/audio/synth.ts";

export interface StoryVariant {
  group: string;
  /** True when fixtures/public/audio/storybook/<variant>.ogg exists. */
  file: boolean;
  synth: Synth;
  dur: number;
}

export const STORY_LIBRARY: Readonly<Record<string, StoryVariant>> = {
`;

const synthLiteral = (s: StoryVariant["synth"]): string => `{ ${Object.entries(s).map(([k, v]) => `${k}: ${JSON.stringify(v)}`).join(", ")} }`;

function renderLibrary(groups: Map<string, [string, StoryVariant][]>): string {
  const lines: string[] = [];
  for (const variants of groups.values())
    for (const [name, v] of variants)
      lines.push(`  ${JSON.stringify(name)}: { group: ${JSON.stringify(v.group)}, file: ${v.file}, synth: ${synthLiteral(v.synth)}, dur: ${v.dur} },`);
  return `${LIBRARY_HEADER}${lines.join("\n")}\n};\n`;
}

const cell = (s: string): string => s.replace(/\|/g, "/");

export function acceptCandidates(o: AcceptOptions): { accepted: string[] } {
  // 1. the kept rows per group, in sheet order
  const kept = new Map<string, { row: CandidateRow; theme: string }[]>();
  for (const name of readdirSync(o.candidatesDir)) {
    const m = /^([a-z0-9-]+)\.json$/.exec(name);
    if (!m || !m[1]) continue;
    const theme = m[1];
    const rows = JSON.parse(readFileSync(join(o.candidatesDir, name), "utf8")) as CandidateRow[];
    const decPath = join(o.candidatesDir, `${theme}.decisions.json`);
    const dec: Decisions = existsSync(decPath) ? (JSON.parse(readFileSync(decPath, "utf8")) as Decisions) : {};
    for (const row of rows) {
      if (row.reason || !row.file || dec[row.file] !== "keep") continue;
      (kept.get(row.group) ?? kept.set(row.group, []).get(row.group)!).push({ row, theme });
    }
  }

  // 2. budget first: what stays in the folder plus what comes in, before anything is touched
  const replaced = new Set(kept.keys());
  const stale = (f: string): boolean => [...replaced].some((g) => new RegExp(`^${g}-\\d+\\.ogg$`).test(f));
  const present = existsSync(o.audioDir) ? readdirSync(o.audioDir) : [];
  const total =
    present.filter((f) => !stale(f)).reduce((a, f) => a + statSync(join(o.audioDir, f)).size, 0) +
    [...kept.values()].flat().reduce((a, { row }) => a + statSync(join(o.candidatesDir, row.file)).size, 0);
  const budget = o.budgetBytes ?? BUDGET_BYTES;
  if (total > budget) throw new Error(`storybook audio would be ${total} bytes, over the budget of ${budget} bytes: keep fewer sounds`);

  // 3. files: copy the new ones first, then delete the stale numbered files that were not overwritten
  mkdirSync(o.audioDir, { recursive: true });
  const accepted: string[] = [];
  const newVariants = new Map<string, [string, StoryVariant][]>();
  const docRows: string[] = [];
  for (const [group, list] of kept) {
    const old = Object.entries(o.baseLibrary).filter(([, v]) => v.group === group).map(([, v]) => v);
    const vs: [string, StoryVariant][] = [];
    list.forEach(({ row }, idx) => {
      const name = `${group}-${idx + 1}`;
      copyFileSync(join(o.candidatesDir, row.file), join(o.audioDir, `${name}.ogg`));
      const fallback = old[idx % Math.max(old.length, 1)];
      if (!fallback) throw new Error(`group ${group} has no entry in the base library`);
      vs.push([name, { group, file: true, synth: fallback.synth, dur: fallback.dur }]);
      accepted.push(name);
      docRows.push(`| ${name} | ${group} | ${cell(row.author)} | ${cell(row.licence)} | ${cell(row.source)} |`);
    });
    newVariants.set(group, vs);
  }
  const keep = new Set(accepted.map((n) => `${n}.ogg`));
  for (const f of present) if (stale(f) && !keep.has(f)) rmSync(join(o.audioDir, f));

  // 4. library: same group order as before, replaced groups swapped in place
  const groups = new Map<string, [string, StoryVariant][]>();
  for (const [name, v] of Object.entries(o.baseLibrary)) {
    if (newVariants.has(v.group)) continue;
    (groups.get(v.group) ?? groups.set(v.group, []).get(v.group)!).push([name, v]);
  }
  const ordered = new Map<string, [string, StoryVariant][]>();
  for (const g of new Set(Object.values(o.baseLibrary).map((v) => v.group))) ordered.set(g, newVariants.get(g) ?? groups.get(g) ?? []);
  writeFileSync(o.libraryPath, renderLibrary(ordered));

  // 5. licence rows: old rows of the replaced groups are dropped, the new ones appended
  const doc = existsSync(o.docPath) ? readFileSync(o.docPath, "utf8") : "";
  const at = doc.indexOf(ROWS_MARKER);
  const head = at >= 0 ? doc.slice(0, at) : `${doc.trimEnd()}\n\n## Accepted files\n\n${TABLE_HEAD}\n`;
  const prev = at >= 0 ? doc.slice(at + ROWS_MARKER.length).split("\n").filter((l) => l.startsWith("| ")) : [];
  const rows = [...prev.filter((l) => !newVariants.has((l.split("|")[2] ?? "").trim())), ...docRows].sort();
  writeFileSync(o.docPath, `${head}${ROWS_MARKER}\n${rows.join("\n")}\n`);
  return { accepted };
}

if (isMain(import.meta.url)) {
  const res = acceptCandidates({
    candidatesDir: CANDIDATES_DIR,
    audioDir: join(REPO_ROOT, "fixtures", "public", "audio", "storybook"),
    libraryPath: join(REPO_ROOT, "packages", "engine", "src", "engines", "storybook", "library.ts"),
    docPath: join(REPO_ROOT, "docs", "assets-audio-storybook.md"),
    baseLibrary: STORY_LIBRARY,
  });
  console.log(`accepted ${res.accepted.length} files: ${res.accepted.join(", ")}`);
}
